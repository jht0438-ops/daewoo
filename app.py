def yoy(new, old):
    return (new / old - 1) * 100 if old else 0

def section_guide(why, how, conclusion):
    st.info(f"왜 분석하나요?\n\n{why}")
    st.info(f"어떻게 분석하나요?\n\n{how}")
    st.success(f"이 탭에서 얻을 수 있는 결론은 무엇인가요?\n\n{conclusion}")

def line_chart(df, x, ys, title, ytitle="억원"):
    fig = go.Figure()
    for y in ys:
        fig.add_trace(go.Scatter(x=df[x], y=df[y], mode="lines+markers+text",
                                 name=y, text=[f"{v:,.0f}" for v in df[y]],
                                 textposition="top center"))
    fig.update_layout(title=title, template="plotly_white", yaxis_title=ytitle,
                      legend_title_text="", margin=dict(l=20,r=20,t=60,b=20))
    return fig

